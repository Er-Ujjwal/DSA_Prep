/* Structure of Linked List Node
class Node {
 public:
    int data;
    Node *next;
    Node(int x) {
        data = x;
        next = nullptr;
    }
};*/

class Solution {
  public:
    int lengthOfLoop(Node *head) {
        Node* temp = head;
        int count = 0;
        unordered_map<Node*, int> mp;
        while (temp){
            count++;
            if (mp[temp]) return count-mp[temp];
            mp[temp] = count;
            temp = temp->next;
        }
        return 0;
    }
};

